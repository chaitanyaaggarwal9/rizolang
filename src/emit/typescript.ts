import type { ResolvedField, ResolvedModel } from "../checker.js";
import { FIELD_TYPES } from "../types.js";
import { VERSION } from "../version.js";

/**
 * Emits TypeScript types. For each model:
 *   - `User`       : the stored record. Server-only; password fields hold a PasswordHash.
 *   - `UserPublic` : `User.public`. Safe for API responses; secret fields are removed.
 *   - `UserInput`  : `User.input`. What a client sends to create a record.
 *
 * The public type is written out field by field (not with Omit<>), so the
 * absence of secret fields can be verified by reading the generated file.
 */
export function emitTypeScript(models: readonly ResolvedModel[], sourceFile: string): string {
  const out: string[] = [
    `// Generated by rizolang ${VERSION} from ${sourceFile}. Do not edit by hand.`,
    "",
    "declare const passwordHashBrand: unique symbol;",
    "/** A salted password hash. A plain string can never be assigned to this type. */",
    "export type PasswordHash = string & { readonly [passwordHashBrand]: true };",
  ];
  for (const model of models) {
    const publicFields = model.fields.filter((f) => !FIELD_TYPES[f.type].secret);
    out.push(
      "",
      "/**",
      ` * ${model.name} as stored in the database (table "${model.table}").`,
      ` * Server-only. Never return this type from an API; use ${model.name}Public.`,
      " */",
      `export interface ${model.name} {`,
      "  readonly id: string;",
      ...model.fields.map((f) => `  readonly ${f.name}: ${storedType(f)};`),
      "}",
      "",
      `/** ${model.name}.public: safe to return from an API. Password fields are never included. */`,
      `export interface ${model.name}Public {`,
      "  readonly id: string;",
      ...publicFields.map((f) => `  readonly ${f.name}: ${storedType(f)};`),
      "}",
      "",
      `/** ${model.name}.input: the data needed to create a ${model.name}. Validated (and passwords hashed) before storage. */`,
      `export interface ${model.name}Input {`,
      ...model.fields.flatMap(inputField),
      "}",
    );
  }
  out.push("");
  return out.join("\n");
}

function storedType(f: ResolvedField): string {
  const ts = FIELD_TYPES[f.type].ts;
  return f.optional ? `${ts} | null` : ts;
}

function inputField(f: ResolvedField): string[] {
  const info = FIELD_TYPES[f.type];
  const lines: string[] = [];
  const doc = describe(f);
  if (doc !== "") lines.push(`  /** ${doc} */`);
  lines.push(
    f.optional
      ? `  readonly ${f.name}?: ${info.tsInput} | null;`
      : `  readonly ${f.name}: ${info.tsInput};`,
  );
  return lines;
}

function describe(f: ResolvedField): string {
  const info = FIELD_TYPES[f.type];
  const notes: string[] = [];
  if (f.type === "Password") notes.push("Plain-text password. Hashed before storage; never stored, returned or logged.");
  if (f.type === "Email") notes.push("Email address, stored in lowercase.");
  if (info.length !== undefined) {
    const min = f.min !== undefined && f.min > 0 ? f.min : undefined;
    if (min !== undefined && f.max !== undefined) notes.push(`${min} to ${f.max} characters.`);
    else if (f.max !== undefined) notes.push(`At most ${f.max} characters.`);
  } else if (info.valueRange !== undefined) {
    notes.push(`Whole number${f.min !== undefined ? `, at least ${f.min}` : ""}${f.max !== undefined ? `${f.min !== undefined ? " and" : ","} at most ${f.max}` : ""}.`);
  }
  if (f.unique) notes.push("Must be unique.");
  return notes.join(" ");
}
