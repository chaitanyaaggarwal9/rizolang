/**
 * Emits `routes.ts`: every endpoint as plain data, with its SQL fixed at
 * compile time. The runtime only binds values to $1, $2, ... placeholders.
 */
export function emitRoutes(
  apis: readonly ResolvedApi[],
  auth: ResolvedAuth | undefined,
  pages: readonly ResolvedPage[],
  sourceFile: string,
  models: readonly ResolvedModel[] = [],
  privacy: readonly string[] | undefined = undefined,
  site: ResolvedSite | undefined = undefined,
): string {
  const app = buildApp(apis, auth, pages, models, privacy, site);
  return [
    `// Generated by rizolang ${VERSION} from ${sourceFile}. Do not edit by hand.`,
    "// Every SQL statement below is fixed at compile time. Requests only supply values",
    "// for the $1, $2, ... parameters, so request data can never change a query.",
    'import type { App } from "./runtime/types.ts";',
    "",
    `export const app: App = ${printTs(app, "")};`,
    "",
  ].join("\n");
}

/** The route table as data (what `routes.ts` contains). */
export function buildApp(
  apis: readonly ResolvedApi[],
  auth: ResolvedAuth | undefined,
  pages: readonly ResolvedPage[] = [],
  allModels: readonly ResolvedModel[] = [],
  privacy: readonly string[] | undefined = undefined,
  site: ResolvedSite | undefined = undefined,
): App {
  // Every model, including ones no endpoint uses (they can still link to accounts).
  const known = [...new Set([...allModels, ...(auth === undefined ? [] : [auth.model]), ...apis.map((a) => a.query.model)])];
  const authSpecs = auth === undefined ? null : authSpec(auth, known);
  const builtIn = authSpecs === null || pages.length === 0 ? [] : authPages(authSpecs, privacy !== undefined);
  const models = [...new Set([...(auth === undefined ? [] : [auth.model]), ...apis.map((a) => a.query.model)])];
  const encrypted = models.flatMap(encryptedColumns);
  const admin = auth !== undefined && authSpecs !== null && auth.roles.includes("admin") ? adminModels(known, auth, authSpecs.account.ghost !== null) : undefined;
  const adminPageRoutes = admin !== undefined && pages.length > 0 ? adminPages(admin, known, auth?.roles ?? []) : [];
  return {
    auth: authSpecs,
    routes: apis.map(route),
    pages: [...pages.map(pageRoute), ...builtIn, ...adminPageRoutes],
    ...(admin !== undefined ? { admin } : {}),
    ...(auth !== undefined && known.some((m) => m.fields.some((f) => f.type === "File"))
      ? { files: { uploads: uploads(known, apis, auth), sweepSql: fileSweepSql(known) } }
      : {}),
    ...(encrypted.length > 0 ? { encrypted } : {}),
    ...(retention(known).length > 0 ? { retention: retention(known) } : {}),
    ...(privacy !== undefined ? { privacy: privacySpec(privacy, known, auth) } : {}),
    ...(site !== undefined ? { site: { name: site.name, color: site.color, ...(site.logo !== undefined ? { logo: logoPath(site.logo) } : {}) } } : {}),
  };
}

/** The address of a model on the admin pages: its table name with "-" for "_". */
export function adminSlug(model: ResolvedModel): string {
  return model.table.replace(/_/g, "-");
}

/** The fields an admin sees: the same public fields as everyone, plus the id. */
function adminFields(model: ResolvedModel): FieldViewSpec[] {
  return [
    { key: "id", label: "ID", type: "ID" },
    ...model.fields.filter((f) => !isHidden(f)).map((f) => ({ key: f.name, label: labelFor(f.name), type: f.type })),
  ];
}

/**
 * For apps with the admin role: every model, with SQL to search and list it
 * (public fields only, in id order) and to delete one record.
 */
function adminModels(models: readonly ResolvedModel[], auth: ResolvedAuth, ghost: boolean): AdminModel[] {
  return models.map((m) => {
    const account = m === auth.model;
    const select = publicSelect(m);
    const table = q(m.table);
    // Search: the exact id, or text anywhere in a public Text or Email field (not encrypted ones), ignoring case.
    const searchable = m.fields.filter((f) => !isHidden(f) && !f.encrypted && (f.type === "Text" || f.type === "Email"));
    const match = [`${q("id")}::text = lower($1::text)`, ...searchable.map((f) => `strpos(lower(${q(f.column)}), lower($1::text)) > 0`)].join(" OR ");
    return {
      name: m.name,
      slug: adminSlug(m),
      account,
      publicKeys: [...select.keys, ...(account ? ["role"] : [])],
      ...encryptedOf(m),
      listSql: `SELECT ${select.sql}${account ? `, ${q("role")}` : ""} FROM ${table} WHERE ($1::text IS NULL OR ${match}) AND ($2::uuid IS NULL OR ${q("id")} > $2::uuid) ORDER BY ${q("id")} LIMIT $3`,
      deleteSql: account ? accountDeleteSql(m, models, ghost, true) : `DELETE FROM ${table} WHERE ${q("id")} = $1`,
    };
  });
}

/** The built-in /admin pages: a list of models, and one page per model. Admins only. */
function adminPages(admin: readonly AdminModel[], models: readonly ResolvedModel[], roles: readonly string[]): PageRoute[] {
  const page = (segments: string[], title: string, items: PageItemSpec[]): PageRoute => ({
    pattern: `/${segments.join("/")}`, path: segments.map((s) => ({ static: s })), access: "login", roles: ["admin"], title, items,
  });
  return [
    page(["admin"], "Admin", [
      { kind: "text", text: "Search, browse and delete records. Only public fields are shown, and every deletion is recorded in the security audit log." },
      ...admin.map((a) => ({ kind: "link", label: a.account ? `${a.name} (accounts)` : a.name, path: `/admin/${a.slug}` } as const)),
    ]),
    ...admin.map((a) => {
      const model = models.find((m) => m.name === a.name);
      return page(["admin", a.slug], a.account ? `${a.name} (accounts)` : a.name, [
        { kind: "link", label: "All models", path: "/admin" },
        { kind: "admin", slug: a.slug, model: a.name, account: a.account, fields: model === undefined ? [] : adminFields(model), roles: a.account ? [...roles] : [] },
      ]);
    }),
  ];
}

/** Where the server serves the logo: /_rizo/logo.png, .jpg or .webp. */
export function logoPath(file: string): string {
  const ext = file.toLowerCase().endsWith(".webp") ? "webp" : file.toLowerCase().endsWith(".png") ? "png" : "jpg";
  return `/_rizo/logo.${ext}`;
}

/** What the privacy notice lists: every model, how each field is kept, and how long records are kept. */
function privacySpec(regions: readonly string[], models: readonly ResolvedModel[], auth: ResolvedAuth | undefined): PrivacySpec {
  return {
    regions: [...regions],
    models: models.map((m) => ({
      name: m.name,
      account: auth?.model === m,
      fields: m.fields.map((f) => ({
        label: labelFor(f.name),
        kind: f.link !== undefined ? `link to ${f.link}` : f.type,
        stored: f.type === "Password" ? "hashed" : f.encrypted ? "encrypted" : f.private ? "private" : "public",
      })),
      keep: m.keep === undefined ? null : { amount: m.keep.amount, unit: m.keep.unit },
    })),
  };
}

/**
 * For each model with `keep`: delete up to 1,000 expired records at a time.
 * Records that another record must link to (a required link) are skipped
 * until that record is gone, so nothing breaks.
 */
function retention(models: readonly ResolvedModel[]): RetentionSpec[] {
  return models.flatMap((m) => {
    if (m.keep === undefined) return [];
    const table = q(m.table);
    const needed = models.flatMap((o) => o.fields.filter((f) => f.link === m.name && !f.optional).map((f) =>
      ` AND NOT EXISTS (SELECT 1 FROM ${q(o.table)} WHERE ${q(o.table)}.${q(f.column)} = "r".${q("id")})`));
    const expired = `"r".${q(CREATED_COLUMN)} < now() - make_interval(${m.keep.unit} => $1)`;
    return [{
      model: m.name,
      amount: m.keep.amount,
      sql: `DELETE FROM ${table} WHERE ${q("id")} IN (SELECT "r".${q("id")} FROM ${table} AS "r" WHERE ${expired}${needed.join("")} ORDER BY "r".${q(CREATED_COLUMN)} LIMIT 1000)`,
    }];
  });
}

/** `{ encrypted: [...] }` for a model with encrypted fields, otherwise nothing. */
function encryptedOf(model: ResolvedModel): { encrypted?: EncryptedField[] } {
  const fields = encryptedFields(model);
  return fields.length > 0 ? { encrypted: fields } : {};
}

/** The encrypted fields of a model, each bound to its table and column. */
function encryptedFields(model: ResolvedModel): EncryptedField[] {
  return model.fields.filter((f) => f.encrypted).map((f) => ({ key: f.name, aad: `${model.table}.${f.column}` }));
}

/** SQL for moving a model's encrypted values to the current key, in batches by id. */
function encryptedColumns(model: ResolvedModel): EncryptedColumn[] {
  const table = q(model.table);
  return model.fields.filter((f) => f.encrypted).map((f) => {
    const col = q(f.column);
    return {
      aad: `${model.table}.${f.column}`,
      select: `SELECT ${q("id")}, ${col} AS "value" FROM ${table} WHERE ${col} IS NOT NULL AND ${col} NOT LIKE $1 AND ${q("id")} > $2::uuid ORDER BY ${q("id")} LIMIT 500`,
      update: `UPDATE ${table} SET ${col} = $2 WHERE ${q("id")} = $1 AND ${col} = $3`,
    };
  });
}

