/**
 * Emits `routes.ts`: every endpoint as plain data, with its SQL fixed at
 * compile time. The runtime only binds values to $1, $2, ... placeholders.
 */
export function emitRoutes(apis: readonly ResolvedApi[], auth: ResolvedAuth | undefined, sourceFile: string): string {
  const app = buildApp(apis, auth);
  return [
    `// Generated by rizolang ${VERSION} from ${sourceFile}. Do not edit by hand.`,
    "// Every SQL statement below is fixed at compile time. Requests only supply values",
    "// for the $1, $2, ... parameters, so request data can never change a query.",
    'import type { App } from "./runtime/types.ts";',
    "",
    `export const app: App = ${printTs(app, "")};`,
    "",
  ].join("\n");
}

/** The route table as data (what `routes.ts` contains). */
export function buildApp(apis: readonly ResolvedApi[], auth: ResolvedAuth | undefined): App {
  return { auth: auth === undefined ? null : authSpec(auth), routes: apis.map(route) };
}

/**
 * Print data as a readable TypeScript literal: SQL in single quotes (so its
 * double-quoted identifiers need no escaping) and small objects on one line.
 */
export function printTs(v: unknown, indent: string): string {
  if (typeof v === "string") return /^[\x20-\x7e]*$/.test(v) && !/['\\]/.test(v) ? `'${v}'` : JSON.stringify(v);
  if (v === null || typeof v !== "object") return JSON.stringify(v);
  const inner = `${indent}  `;
  if (Array.isArray(v)) {
    if (v.length === 0) return "[]";
    if (v.every((x) => x === null || typeof x !== "object")) return `[${v.map((x) => printTs(x, inner)).join(", ")}]`;
    return `[\n${v.map((x) => inner + printTs(x, inner)).join(",\n")},\n${indent}]`;
  }
  const entries = Object.entries(v);
  const key = (k: string): string => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : JSON.stringify(k));
  if (entries.every(([, x]) => x === null || typeof x !== "object")) {
    return `{ ${entries.map(([k, x]) => `${key(k)}: ${printTs(x, inner)}`).join(", ")} }`;
  }
  return `{\n${entries.map(([k, x]) => `${inner}${key(k)}: ${printTs(x, inner)}`).join(",\n")},\n${indent}}`;
}

/** Emits `server.ts`, the entry point of the generated app. */
export function emitServer(sourceFile: string): string {
  return [
    `// Generated by rizolang ${VERSION} from ${sourceFile}. Do not edit by hand.`,
    "// Run with: DATABASE_URL=postgres://... node server.ts",
    'import { app } from "./routes.ts";',
    'import { startServer } from "./runtime/server.ts";',
    "",
    "startServer(app);",
    "",
  ].join("\n");
}

/** Emits `migrate.ts`, which applies the files in `migrations/` to the database. */
export function emitMigrate(sourceFile: string): string {
  return [
    `// Generated by rizolang ${VERSION} from ${sourceFile}. Do not edit by hand.`,
    "// Run with: DATABASE_URL=postgres://... node migrate.ts",
    "// For a database created from schema.sql before migrations existed: node migrate.ts --baseline",
    'import { runMigrations } from "./runtime/migrate.ts";',
    "",
    'await runMigrations(new URL("./migrations/", import.meta.url));',
    "",
  ].join("\n");
}

