function pageRoute(page: ResolvedPage): PageRoute {
  return {
    pattern: page.path,
    path: page.segments.map((s) => {
      if (s.kind === "static") return { static: s.value };
      const param = page.params.find((x) => x.name === s.name);
      return { param: s.name, kind: param?.type ?? "Text" };
    }),
    access: page.access,
    roles: page.roles,
    title: page.title,
    items: page.items.map((item): PageItemSpec => {
      if (item.kind === "text" || item.kind === "link") return item;
      if (item.kind === "form") {
        const r = route(item.api);
        const method = item.api.method;
        if (method !== "POST" && method !== "PUT" && method !== "PATCH") throw new Error(`form with ${method}`);
        return {
          kind: "form",
          method,
          endpoint: item.api.path,
          fields: (r.body ?? []).map(formField),
          submit: item.api.query.action === "create" ? "Save" : "Save changes",
          prefill: item.prefill?.path ?? null,
          then: page.then ?? null,
        };
      }
      if (item.kind === "button") {
        if (page.then === undefined) throw new Error("button without then go");
        return { kind: "button", label: item.label, method: "DELETE", endpoint: item.api.path, then: page.then };
      }
      return {
        kind: "show",
        endpoint: item.api.path,
        mode: item.mode,
        model: item.api.query.model.name,
        fields: item.fields.map((f) => {
          const linked = item.api.expand.find((x) => x.field.name === f.key);
          return { key: f.key, label: f.label, type: f.type, ...(linked !== undefined ? { display: displayField(linked.model) } : {}) };
        }),
        detail: item.detail ?? null,
      };
    }),
  };
}

/**
 * Print data as a readable TypeScript literal: SQL in single quotes (so its
 * double-quoted identifiers need no escaping) and small objects on one line.
 */
export function printTs(v: unknown, indent: string): string {
  if (typeof v === "string") return /^[\x20-\x7e]*$/.test(v) && !/['\\]/.test(v) ? `'${v}'` : JSON.stringify(v);
  if (v === null || typeof v !== "object") return JSON.stringify(v);
  const inner = `${indent}  `;
  if (Array.isArray(v)) {
    if (v.length === 0) return "[]";
    if (v.every((x) => x === null || typeof x !== "object")) return `[${v.map((x) => printTs(x, inner)).join(", ")}]`;
    return `[\n${v.map((x) => inner + printTs(x, inner)).join(",\n")},\n${indent}]`;
  }
  const entries = Object.entries(v);
  const key = (k: string): string => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : JSON.stringify(k));
  if (entries.every(([, x]) => x === null || typeof x !== "object")) {
    return `{ ${entries.map(([k, x]) => `${key(k)}: ${printTs(x, inner)}`).join(", ")} }`;
  }
  return `{\n${entries.map(([k, x]) => `${inner}${key(k)}: ${printTs(x, inner)}`).join(",\n")},\n${indent}}`;
}

