// ------------------------------------------------------------------ helpers

const quoteKey = (key: string): string => {
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(key)) throw new Error(`unsafe key: ${key}`);
  return `"${key}"`;
};

/** `"id", "title", "author_id" AS "author"`: only public columns, renamed to JSON keys. */
function publicSelect(model: ResolvedModel): { sql: string; keys: string[] } {
  const fields = model.fields.filter((f) => !isHidden(f));
  const cols = [q("id"), ...fields.map((f) => (f.column === f.name ? q(f.column) : `${q(f.column)} AS ${quoteKey(f.name)}`))];
  return { sql: cols.join(", "), keys: ["id", ...fields.map((f) => f.name)] };
}

function fieldSpec(f: ResolvedField, required: boolean): FieldSpec {
  const info = FIELD_TYPES[f.type];
  const spec: { -readonly [K in keyof FieldSpec]: FieldSpec[K] } = {
    key: f.name,
    kind: f.type,
    required,
    nullable: f.optional,
  };
  if (info.length !== undefined) {
    if (f.min !== undefined && f.min > 0) spec.min = f.min;
    if (f.max !== undefined) spec.max = f.max;
  } else if (info.valueRange !== undefined) {
    if (f.min !== undefined) spec.min = f.min;
    if (f.max !== undefined) spec.max = f.max;
  }
  return spec;
}

/** PostgreSQL type used to read a cursor's sort value back from text. */
const CURSOR_CAST: Readonly<Record<FieldTypeName, string>> = {
  Text: "text", Email: "text", Number: "integer", Bool: "boolean", Date: "timestamptz", ID: "uuid", Password: "text",
};

class Params {
  readonly values: ValueSource[] = [];
  add(source: ValueSource): string {
    this.values.push(source);
    return `$${this.values.length}`;
  }
  value(v: ResolvedValue): string {
    switch (v.kind) {
      case "me": return this.add({ from: "me" });
      case "param": return this.add({ from: "path", name: v.name });
      default: return this.add({ from: "const", value: v.value });
    }
  }
}

function route(api: ResolvedApi): Route {
  const { query } = api;
  const model = query.model;
  const table = q(model.table);
  const select = publicSelect(model);
  const p = new Params();

  const path: PathPart[] = api.segments.map((s) => {
    if (s.kind === "static") return { static: s.value };
    const param = api.params.find((x) => x.name === s.name);
    if (param === undefined) throw new Error(`unused path parameter ${s.name}`);
    return { param: s.name, kind: param.type };
  });

  const byId = (idParam: string): string => {
    let where = `${q("id")} = ${p.add({ from: "path", name: idParam })}`;
    if (api.owner !== undefined) {
      const owner = `${q(api.owner.column)} = ${p.add({ from: "me" })}`;
      where += api.ownerBypassRoles.length > 0
        ? ` AND (${owner} OR ${p.add({ from: "hasRole", roles: api.ownerBypassRoles })})`
        : ` AND ${owner}`;
    }
    return where;
  };

  let sql: string;
  let body: FieldSpec[] | null = null;
  let page: Route["page"] = null;
  let result: Route["result"];
  switch (query.action) {
    case "find":
      sql = `SELECT ${select.sql} FROM ${table} WHERE ${byId(query.idParam)}`;
      result = "one";
      break;
    case "delete":
      sql = `DELETE FROM ${table} WHERE ${byId(query.idParam)}`;
      result = "none";
      break;
    case "list": {
      // Keyset pagination: rows come in a fixed order (sort column, then id),
      // and `?after=<cursor>` continues after the last row of the previous page.
      const where = query.filters.map((fv: FieldValue) => `${q(fv.field.column)} = ${p.value(fv.value)}`);
      const of = query.order.field;
      const dir = query.order.descending ? "DESC" : "ASC";
      const cmp = query.order.descending ? "<" : ">";
      const hasCursor = p.add({ from: "cursorSet" });
      let cursorSelect = "";
      let order: string;
      if (of === undefined) {
        where.push(`(${hasCursor} IS NOT TRUE OR ${q("id")} ${cmp} ${p.add({ from: "cursorId" })}::uuid)`);
        order = `${q("id")} ${dir}`;
      } else {
        const value = p.add({ from: "cursorValue" });
        const id = p.add({ from: "cursorId" });
        where.push(`(${hasCursor} IS NOT TRUE OR (${q(of.column)}, ${q("id")}) ${cmp} (${value}::${CURSOR_CAST[of.type]}, ${id}::uuid))`);
        // The sort value travels in the cursor as PostgreSQL text, so it round-trips exactly.
        cursorSelect = `, ${q(of.column)}::text AS "_cursor"`;
        order = `${q(of.column)} ${dir}, ${q("id")} ${dir}`;
      }
      sql = `SELECT ${select.sql}${cursorSelect} FROM ${table} WHERE ${where.join(" AND ")} ORDER BY ${order} LIMIT ${p.add({ from: "pageLimit" })}`;
      page = { max: query.limit, order: of === undefined ? null : of.type };
      result = "list";
      break;
    }
    case "create": {
      body = query.bodyFields.map((f) => fieldSpec(f, !f.optional));
      const cols: string[] = [];
      const vals: string[] = [];
      for (const f of query.bodyFields) {
        cols.push(q(f.column));
        vals.push(p.add({ from: "body", key: f.name }));
      }
      for (const a of query.assigns) {
        cols.push(q(a.field.column));
        vals.push(p.value(a.value));
      }
      sql = `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${vals.join(", ")}) RETURNING ${select.sql}`;
      result = "created";
      break;
    }
    case "update": {
      body = query.bodyFields.map((f) => fieldSpec(f, false));
      const where = byId(query.idParam);
      const sets = query.bodyFields.map((f) => {
        const provided = p.add({ from: "provided", key: f.name });
        const value = p.add({ from: "body", key: f.name });
        return `${q(f.column)} = CASE WHEN ${provided} THEN ${value} ELSE ${q(f.column)} END`;
      });
      sql = `UPDATE ${table} SET ${sets.join(", ")} WHERE ${where} RETURNING ${select.sql}`;
      result = "one";
      break;
    }
  }
  return {
    method: api.method,
    pattern: api.path,
    path,
    access: api.access,
    roles: api.roles,
    body,
    sql,
    values: p.values,
    result,
    page,
    publicKeys: select.keys,
    model: model.name,
  };
}

function authSpec(auth: ResolvedAuth): AuthSpec {
  const model = auth.model;
  const table = q(model.table);
  const select = publicSelect(model);
  // Links from the auth model to itself cannot be set at signup (there is no "me" yet).
  const fields = model.fields.filter((f) => f.link !== model.name);
  const p = new Params();
  const cols = fields.map((f) => q(f.column));
  const vals = fields.map((f) => p.add({ from: "body", key: f.name }));
  // Profile updates: every field except the login email, the password and
  // links to the auth model (and the hidden role column, which is not a field).
  const profileFields = model.fields.filter(
    (f) => f !== auth.loginField && f !== auth.passwordField && f.link !== model.name,
  );
  const pp = new Params();
  const id = pp.add({ from: "me" });
  const sets = profileFields.map((f) => {
    const provided = pp.add({ from: "provided", key: f.name });
    const value = pp.add({ from: "body", key: f.name });
    return `${q(f.column)} = CASE WHEN ${provided} THEN ${value} ELSE ${q(f.column)} END`;
  });
  return {
    model: model.name,
    account: {
      password: { ...fieldSpec(auth.passwordField, true), key: "newPassword" },
      hashSql: `SELECT ${q(auth.passwordField.column)} AS "hash" FROM ${table} WHERE ${q("id")} = $1`,
      setPasswordSql: `UPDATE ${table} SET ${q(auth.passwordField.column)} = $2 WHERE ${q("id")} = $1`,
      deleteSql: `DELETE FROM ${table} WHERE ${q("id")} = $1`,
      profile: profileFields.length === 0
        ? null
        : {
            body: profileFields.map((f) => fieldSpec(f, false)),
            sql: `UPDATE ${table} SET ${sets.join(", ")} WHERE ${q("id")} = ${id} RETURNING ${select.sql}`,
            values: pp.values,
          },
    },
    signup: {
      body: fields.map((f) => fieldSpec(f, !f.optional)),
      sql: `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${vals.join(", ")}) RETURNING ${select.sql}`,
      values: p.values,
    },
    loginKey: auth.loginField.name,
    passwordKey: auth.passwordField.name,
    loginSql: `SELECT ${q("id")}, ${q(auth.passwordField.column)} AS "hash" FROM ${table} WHERE ${q(auth.loginField.column)} = $1`,
    meSql: `SELECT ${select.sql} FROM ${table} WHERE ${q("id")} = $1`,
    publicKeys: select.keys,
    roles: auth.roles,
    roleSql: auth.roles.length > 0 ? `SELECT ${q("role")} FROM ${table} WHERE ${q("id")} = $1` : "",
    setRoleSql: auth.roles.length > 0 ? `UPDATE ${table} SET ${q("role")} = $2 WHERE ${q("id")} = $1 RETURNING ${q("id")}, ${q("role")}` : "",
    grantAdminSql: auth.roles.length > 0
      ? `UPDATE ${table} SET ${q("role")} = ${roleLiteral("admin")} WHERE ${q(auth.loginField.column)} = ANY($1) AND ${q("role")} IS DISTINCT FROM ${roleLiteral("admin")}`
      : "",
  };
}
