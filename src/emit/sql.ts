import type { ResolvedAuth } from "../check-api.js";
import type { ResolvedField, ResolvedModel } from "../checker.js";
import { FIELD_TYPES } from "../types.js";
import { VERSION } from "../version.js";

/** Name of the table that stores login sessions. Model tables can never start with "_". */
export const SESSIONS_TABLE = "_rizo_sessions";

/** Quote a compiler-validated identifier. Names contain only [a-z0-9_], so this is always safe. */
export const q = (identifier: string): string => {
  if (!/^[a-z_][a-z0-9_]*$/.test(identifier)) throw new Error(`unsafe identifier: ${identifier}`);
  return `"${identifier}"`;
};

/**
 * Emits a PostgreSQL schema. Identifiers are always double-quoted; the lexer
 * only allows letters and digits in names, so no identifier can break out of
 * its quotes.
 */
export function emitSql(models: readonly ResolvedModel[], auth: ResolvedAuth | undefined, sourceFile: string): string {
  const out: string[] = [
    `-- Generated by rizolang ${VERSION} from ${sourceFile}. Do not edit by hand.`,
    "-- Requires PostgreSQL 13 or newer (uses gen_random_uuid()).",
    "",
    "BEGIN;",
  ];
  for (const model of models) {
    const cols = [
      `  ${q("id")} UUID PRIMARY KEY DEFAULT gen_random_uuid()`,
      ...model.fields.map(columnSql),
    ];
    if (auth !== undefined && auth.model === model && auth.roles.length > 0) {
      cols.push(`  -- role: assigned by admins only, never accepted from requests or returned\n  ${q("role")} TEXT CHECK (${q("role")} IN (${auth.roles.map(roleLiteral).join(", ")}))`);
    }
    out.push("", `CREATE TABLE ${q(model.table)} (`, cols.join(",\n"), ");");
  }

  // Foreign keys are added after all tables exist, so models may link to
  // each other in any order (and to themselves).
  const links = models.flatMap((m) => m.fields.filter((f) => f.link !== undefined).map((f) => ({ m, f })));
  if (links.length > 0) out.push("");
  for (const { m, f } of links) {
    const target = models.find((x) => x.name === f.link);
    if (target === undefined) throw new Error(`unresolved link ${m.name}.${f.name}`);
    out.push(
      `ALTER TABLE ${q(m.table)} ADD FOREIGN KEY (${q(f.column)}) REFERENCES ${q(target.table)} (${q("id")}) ON DELETE ${f.optional ? "SET NULL" : "RESTRICT"};`,
      `CREATE INDEX ON ${q(m.table)} (${q(f.column)});`,
    );
  }

  if (auth !== undefined) {
    out.push(
      "",
      "-- Login sessions. Only a SHA-256 hash of each session token is stored.",
      `CREATE TABLE ${q(SESSIONS_TABLE)} (`,
      `  ${q("token_hash")} TEXT PRIMARY KEY,`,
      `  ${q("user_id")} UUID NOT NULL REFERENCES ${q(auth.model.table)} (${q("id")}) ON DELETE CASCADE,`,
      `  ${q("created_at")} TIMESTAMPTZ NOT NULL DEFAULT now(),`,
      `  ${q("expires_at")} TIMESTAMPTZ NOT NULL`,
      ");",
      `CREATE INDEX ON ${q(SESSIONS_TABLE)} (${q("user_id")});`,
    );
  }
  out.push("", "COMMIT;", "");
  return out.join("\n");
}

/** A role name as a SQL string literal. Role names are validated as [a-z][A-Za-z0-9]*. */
export const roleLiteral = (role: string): string => {
  if (!/^[a-z][A-Za-z0-9]*$/.test(role)) throw new Error(`unsafe role: ${role}`);
  return `'${role}'`;
};

function columnSql(f: ResolvedField): string {
  const info = FIELD_TYPES[f.type];
  const col = q(f.column);
  const parts = [`  ${col} ${info.sql}`];
  if (!f.optional) parts.push("NOT NULL");
  if (f.unique) parts.push("UNIQUE");

  const checks: string[] = [];
  if (info.secret) {
    // Password limits apply to the plain-text input, not to the stored hash.
  } else if (info.length !== undefined) {
    checks.push(...rangeChecks(`char_length(${col})`, f.min !== undefined && f.min > 0 ? f.min : undefined, f.max));
  } else if (info.valueRange !== undefined) {
    checks.push(...rangeChecks(col, f.min, f.max));
  }
  if (f.type === "Email") {
    checks.push(`${col} = lower(${col})`);
    checks.push(`${col} ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'`);
  }
  if (checks.length > 0) parts.push(`CHECK (${checks.join(" AND ")})`);

  const line = parts.join(" ");
  return info.secret ? `  -- ${f.name}: stored only as a salted hash, never as plain text\n${line}` : line;
}

function rangeChecks(expr: string, min: number | undefined, max: number | undefined): string[] {
  if (min !== undefined && max !== undefined) return [`${expr} BETWEEN ${min} AND ${max}`];
  if (min !== undefined) return [`${expr} >= ${min}`];
  if (max !== undefined) return [`${expr} <= ${max}`];
  return [];
}
