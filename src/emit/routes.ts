// ------------------------------------------------------------------ helpers

const quoteKey = (key: string): string => {
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(key)) throw new Error(`unsafe key: ${key}`);
  return `"${key}"`;
};

/**
 * Public columns, with each expanded link (`with author`) as a JSON object of
 * the linked record's public fields, read by primary key in a subquery: still
 * one query, and no join to make column names ambiguous.
 */
function expandedSelect(model: ResolvedModel, expand: ResolvedApi["expand"]): { sql: string; keys: string[] } {
  const fields = model.fields.filter((f) => !isHidden(f));
  const cols = [`${q(model.table)}.${q("id")}`, ...fields.map((f) => {
    const e = expand.findIndex((x) => x.field === f);
    const linked = expand[e];
    if (linked === undefined) return `${q(model.table)}.${q(f.column)} AS ${quoteKey(f.name)}`;
    const alias = q(`l${e + 1}`);
    const inner = publicSelect(linked.model);
    const pairs = inner.keys.map((key, i) => {
      const field = i === 0 ? undefined : linked.model.fields.find((x) => x.name === key);
      const col = `${alias}.${q(field?.column ?? "id")}`;
      // Dates in the same format as top-level ones: UTC, milliseconds, "Z".
      const value = field?.type === "Date" && !field.encrypted ? `to_char(${col} AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')` : col;
      return `'${key}', ${value}`;
    });
    // jsonb_build_object takes at most 100 arguments, so large records are built in parts and joined.
    const parts: string[] = [];
    for (let i = 0; i < pairs.length; i += 40) parts.push(`jsonb_build_object(${pairs.slice(i, i + 40).join(", ")})`);
    return `(SELECT ${parts.join(" || ")} FROM ${q(linked.model.table)} AS ${alias} WHERE ${alias}.${q("id")} = ${q(model.table)}.${q(f.column)}) AS ${quoteKey(f.name)}`;
  })];
  return { sql: cols.join(", "), keys: ["id", ...fields.map((f) => f.name)] };
}

/** The first public text field of a model, shown for its records on pages ("by Alice"); "id" if none. */
function displayField(model: ResolvedModel): string {
  return model.fields.find((f) => !isHidden(f) && f.link === undefined && (f.type === "Text" || f.type === "Email"))?.name ?? "id";
}

/** `"id", "title", "author_id" AS "author"`: only public columns, renamed to JSON keys. */
function publicSelect(model: ResolvedModel): { sql: string; keys: string[] } {
  const fields = model.fields.filter((f) => !isHidden(f));
  const cols = [q("id"), ...fields.map((f) => (f.column === f.name ? q(f.column) : `${q(f.column)} AS ${quoteKey(f.name)}`))];
  return { sql: cols.join(", "), keys: ["id", ...fields.map((f) => f.name)] };
}

function fieldSpec(f: ResolvedField, required: boolean, model?: ResolvedModel): FieldSpec {
  const info = FIELD_TYPES[f.type];
  const spec: { -readonly [K in keyof FieldSpec]: FieldSpec[K] } = {
    key: f.name,
    kind: f.type,
    required,
    nullable: f.optional,
  };
  if (f.type === "File") {
    if (f.max !== undefined) spec.max = f.max;
    spec.accept = [...(f.accept ?? [])];
    if (model !== undefined) spec.upload = `/_rizo/uploads/${uploadPath(model, f)}`;
  } else if (info.length !== undefined) {
    if (f.min !== undefined && f.min > 0) spec.min = f.min;
    if (f.max !== undefined) spec.max = f.max;
  } else if (info.valueRange !== undefined) {
    if (f.min !== undefined) spec.min = f.min;
    if (f.max !== undefined) spec.max = f.max;
  }
  return spec;
}

/** PostgreSQL type used to read a cursor's sort value back from text. */
const CURSOR_CAST: Readonly<Record<FieldTypeName, string>> = {
  Text: "text", Email: "text", Number: "integer", Bool: "boolean", Date: "timestamptz", ID: "uuid", Password: "text", File: "text",
};

/**
 * One list filter. A query parameter (`?q`) is optional: when it is missing
 * (null), the filter is skipped. `contains` uses strpos, so % and _ in the
 * search are plain characters.
 */
function filterSql(fv: FieldValue, p: Params): string {
  const col = q(fv.field.column);
  const ref = fv.value.kind === "query"
    ? `${p.add({ from: "query", name: fv.value.name })}::${fv.op === "contains" ? "text" : CURSOR_CAST[fv.field.type]}`
    : p.value(fv.value);
  const test = fv.op === "contains"
    ? `strpos(lower(${col}), lower(${ref})) > 0`
    : fv.op === "!=" ? `${col} IS DISTINCT FROM ${ref}` : `${col} ${fv.op} ${ref}`;
  return fv.value.kind === "query" ? `(${ref} IS NULL OR ${test})` : test;
}

class Params {
  readonly values: ValueSource[] = [];
  add(source: ValueSource): string {
    this.values.push(source);
    return `$${this.values.length}`;
  }
  value(v: ResolvedValue): string {
    switch (v.kind) {
      case "me": return this.add({ from: "me" });
      case "param": return this.add({ from: "path", name: v.name });
      case "query": return this.add({ from: "query", name: v.name });
      default: return this.add({ from: "const", value: v.value });
    }
  }
}

/** The address under /_rizo/uploads/ where files for a File field are uploaded. */
export function uploadPath(model: ResolvedModel, f: ResolvedField): string {
  return `${adminSlug(model)}/${f.name}`;
}

/** "<table>.<column>": the field an upload is made for. */
const fileTarget = (model: ResolvedModel, f: ResolvedField): string => `${model.table}.${f.column}`;

/** The File fields of a body, with SQL to check (on update) whether a value is the record's current file. */
function fileFields(model: ResolvedModel, body: readonly ResolvedField[], id: ValueSource | undefined): FileField[] {
  return body.filter((f) => f.type === "File").map((f) => ({
    key: f.name,
    field: fileTarget(model, f),
    ...(id !== undefined ? { current: { sql: `SELECT 1 FROM ${q(model.table)} WHERE ${q("id")} = $1 AND ${q(f.column)} = $2`, id } } : {}),
  }));
}

/**
 * Upload addresses for every File field that some endpoint (or the profile)
 * accepts, with who may upload: the union of what those endpoints allow.
 */
function uploads(models: readonly ResolvedModel[], apis: readonly ResolvedApi[], auth: ResolvedAuth): UploadSpec[] {
  return models.flatMap((m) => m.fields.filter((f) => f.type === "File").flatMap((f) => {
    const taking = apis.filter((a) => a.query.model === m && "bodyFields" in a.query && a.query.bodyFields.includes(f));
    const profile = m === auth.model && f !== auth.loginField && f !== auth.passwordField;
    if (taking.length === 0 && !profile) return [];
    const open = profile || taking.some((a) => a.roles.length === 0);
    return [{
      path: uploadPath(m, f),
      field: fileTarget(m, f),
      accept: [...(f.accept ?? [])],
      max: f.max ?? 0,
      roles: open ? [] : [...new Set(taking.flatMap((a) => a.roles))],
      endpoints: taking.map((a) => `${a.method} ${a.path}`),
    }];
  }));
}

/** Deletes up to 100 files that are at least a day old and that no record uses. */
function fileSweepSql(models: readonly ResolvedModel[]): string {
  const files = q(FILES_TABLE);
  const unused = models.flatMap((m) => m.fields.filter((f) => f.type === "File").map((f) =>
    ` AND NOT EXISTS (SELECT 1 FROM ${q(m.table)} WHERE ${q(m.table)}.${q(f.column)} = "f".${q("id")})`));
  return `DELETE FROM ${files} WHERE ${q("id")} IN (SELECT "f".${q("id")} FROM ${files} AS "f" WHERE "f".${q("created_at")} < now() - interval '1 day'${unused.join("")} ORDER BY "f".${q("created_at")} LIMIT 100) RETURNING ${q("id")}, ${q("type")}`;
}

function route(api: ResolvedApi): Route {
  const { query } = api;
  const model = query.model;
  const table = q(model.table);
  const select = api.expand.length > 0 ? expandedSelect(model, api.expand) : publicSelect(model);
  const p = new Params();

  const path: PathPart[] = api.segments.map((s) => {
    if (s.kind === "static") return { static: s.value };
    const param = api.params.find((x) => x.name === s.name);
    if (param === undefined) throw new Error(`unused path parameter ${s.name}`);
    return { param: s.name, kind: param.type };
  });

  const byId = (idParam: string): string => {
    let where = `${q("id")} = ${p.add({ from: "path", name: idParam })}`;
    if (api.owner !== undefined) {
      const owner = `${q(api.owner.column)} = ${p.add({ from: "me" })}`;
      where += api.ownerBypassRoles.length > 0
        ? ` AND (${owner} OR ${p.add({ from: "hasRole", roles: api.ownerBypassRoles })})`
        : ` AND ${owner}`;
    }
    return where;
  };

  let sql: string;
  let body: FieldSpec[] | null = null;
  let page: Route["page"] = null;
  let files: FileField[] = [];
  let queryList: Route["query"] | undefined;
  let result: Route["result"];
  switch (query.action) {
    case "find":
      sql = `SELECT ${select.sql} FROM ${table} WHERE ${byId(query.idParam)}`;
      result = "one";
      break;
    case "delete":
      sql = `DELETE FROM ${table} WHERE ${byId(query.idParam)}`;
      result = "none";
      break;
    case "list": {
      // Keyset pagination: rows come in a fixed order (sort column, then id),
      // and `?after=<cursor>` continues after the last row of the previous page.
      const where = query.filters.map((fv: FieldValue) => filterSql(fv, p));
      const of = query.order.field;
      const dir = query.order.descending ? "DESC" : "ASC";
      const cmp = query.order.descending ? "<" : ">";
      const hasCursor = p.add({ from: "cursorSet" });
      let cursorSelect = "";
      let order: string;
      if (of === undefined) {
        where.push(`(${hasCursor} IS NOT TRUE OR ${q("id")} ${cmp} ${p.add({ from: "cursorId" })}::uuid)`);
        order = `${q("id")} ${dir}`;
      } else {
        const value = p.add({ from: "cursorValue" });
        const id = p.add({ from: "cursorId" });
        where.push(`(${hasCursor} IS NOT TRUE OR (${q(of.column)}, ${q("id")}) ${cmp} (${value}::${CURSOR_CAST[of.type]}, ${id}::uuid))`);
        // The sort value travels in the cursor as PostgreSQL text, so it round-trips exactly.
        cursorSelect = `, ${q(of.column)}::text AS "_cursor"`;
        order = `${q(of.column)} ${dir}, ${q("id")} ${dir}`;
      }
      sql = `SELECT ${select.sql}${cursorSelect} FROM ${table} WHERE ${where.join(" AND ")} ORDER BY ${order} LIMIT ${p.add({ from: "pageLimit" })}`;
      page = { max: query.limit, order: of === undefined ? null : of.type };
      if (query.queryParams.length > 0) queryList = query.queryParams.map((x) => ({ name: x.name, kind: x.type, ...(x.max !== undefined ? { max: x.max } : {}) }));
      result = "list";
      break;
    }
    case "create": {
      body = query.bodyFields.map((f) => fieldSpec(f, !f.optional, model));
      const cols: string[] = [];
      const vals: string[] = [];
      for (const f of query.bodyFields) {
        cols.push(q(f.column));
        vals.push(p.add({ from: "body", key: f.name }));
      }
      for (const a of query.assigns) {
        cols.push(q(a.field.column));
        vals.push(p.value(a.value));
      }
      sql = `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${vals.join(", ")}) RETURNING ${select.sql}`;
      files = fileFields(model, query.bodyFields, undefined);
      result = "created";
      break;
    }
    case "update": {
      body = query.bodyFields.map((f) => fieldSpec(f, false, model));
      const where = byId(query.idParam);
      const sets = query.bodyFields.map((f) => {
        const provided = p.add({ from: "provided", key: f.name });
        const value = p.add({ from: "body", key: f.name });
        return `${q(f.column)} = CASE WHEN ${provided} THEN ${value} ELSE ${q(f.column)} END`;
      });
      sql = `UPDATE ${table} SET ${sets.join(", ")} WHERE ${where} RETURNING ${select.sql}`;
      files = fileFields(model, query.bodyFields, { from: "path", name: query.idParam });
      result = "one";
      break;
    }
  }
  return {
    method: api.method,
    pattern: api.path,
    path,
    access: api.access,
    roles: api.roles,
    rateLimit: api.rateLimit,
    body,
    sql,
    values: p.values,
    result,
    page,
    publicKeys: select.keys,
    model: model.name,
    ...(queryList !== undefined ? { query: queryList } : {}),
    ...(files.length > 0 ? { files } : {}),
    ...(api.expand.length > 0
      ? { expanded: api.expand.map((x) => ({ key: x.field.name, publicKeys: publicSelect(x.model).keys, ...encryptedOf(x.model) })) }
      : {}),
    ...(encryptedFields(model).length > 0 ? { encrypted: encryptedFields(model) } : {}),
  };
}

/** `"id", "title", "author_id" AS "author"`: every column except password hashes (for the owner's own export). */
function exportSelect(model: ResolvedModel, withRole: boolean): string {
  const fields = model.fields.filter((f) => f.type !== "Password");
  const cols = [q("id"), ...fields.map((f) => (f.column === f.name ? q(f.column) : `${q(f.column)} AS ${quoteKey(f.name)}`))];
  if (withRole) cols.push(q("role"));
  return cols.join(", ");
}

/** A placeholder for one field of the "Deleted user" account: null to leave empty, undefined if none can be made. */
function ghostValue(f: ResolvedField): GhostValue | null | undefined {
  if (f.optional) return null;
  if (f.link !== undefined) return undefined; // a required link to another record can't be filled in
  const info = FIELD_TYPES[f.type];
  switch (f.type) {
    case "Password": return { kind: "noPassword" };
    case "File": return undefined; // a required file can't be made up (and File fields on accounts are always optional)
    case "Email": return { kind: "email", max: f.max ?? info.length?.defaultMax ?? 254 };
    case "Bool": return { kind: "fixed", value: false };
    case "ID": return { kind: "uuid" };
    case "Date": return f.unique ? { kind: "date" } : { kind: "fixed", value: "1970-01-01T00:00:00.000Z" };
    case "Number": {
      const min = f.min ?? info.valueRange?.lowest ?? 0;
      const max = f.max ?? info.valueRange?.highest ?? 0;
      return f.unique ? { kind: "number", min, max } : { kind: "fixed", value: Math.min(Math.max(0, min), max) };
    }
    case "Text": {
      const max = f.max ?? info.length?.defaultMax ?? 10_000;
      if (f.unique) return { kind: "unique", max };
      const text = "Deleted user".slice(0, max);
      return { kind: "fixed", value: text.padEnd(Math.min(f.min ?? 0, max), ".") };
    }
  }
}

/**
 * Deletes an account ($1). With `ghost`, its records that need an owner are
 * first given to the "Deleted user" account ($2), in the same statement.
 * With `notAdmin` (admin pages), nothing happens if the account is an admin,
 * checked in the statement itself, so a role change can't slip in between.
 */
function accountDeleteSql(model: ResolvedModel, models: readonly ResolvedModel[], ghost: boolean, notAdmin: boolean): string {
  const table = q(model.table);
  const guard = notAdmin ? ` AND ${q("role")} IS DISTINCT FROM ${roleLiteral("admin")}` : "";
  const target = notAdmin ? ` AND EXISTS (SELECT 1 FROM ${table} WHERE ${q("id")} = $1${guard})` : "";
  const requiredLinks = models.filter((m) => m !== model).flatMap((m) => m.fields.filter((f) => f.link === model.name && !f.optional).map((f) => ({ m, f })));
  const moves = requiredLinks.map(({ m, f }, i) => `"moved${i + 1}" AS (UPDATE ${q(m.table)} SET ${q(f.column)} = $2 WHERE ${q(f.column)} = $1${target})`);
  return ghost
    ? `WITH ${moves.join(", ")} DELETE FROM ${table} WHERE ${q("id")} = $1${guard}`
    : `DELETE FROM ${table} WHERE ${q("id")} = $1${guard}`;
}

function authSpec(auth: ResolvedAuth, models: readonly ResolvedModel[]): AuthSpec {
  const model = auth.model;
  const table = q(model.table);
  const select = publicSelect(model);
  // Links from the auth model to itself cannot be set at signup (there is no "me" yet).
  // Nor files: uploading needs a login, so they are added later on the account page.
  const fields = model.fields.filter((f) => f.link !== model.name && f.type !== "File");
  const p = new Params();
  const cols = fields.map((f) => q(f.column));
  const vals = fields.map((f) => p.add({ from: "body", key: f.name }));
  // Profile updates: every field except the login email, the password and
  // links to the auth model (and the hidden role column, which is not a field).
  const profileFields = model.fields.filter(
    (f) => f !== auth.loginField && f !== auth.passwordField && f.link !== model.name,
  );
  const pp = new Params();
  const id = pp.add({ from: "me" });
  const sets = profileFields.map((f) => {
    const provided = pp.add({ from: "provided", key: f.name });
    const value = pp.add({ from: "body", key: f.name });
    return `${q(f.column)} = CASE WHEN ${provided} THEN ${value} ELSE ${q(f.column)} END`;
  });
  // Deleting an account gives its records to the shared "Deleted user" account,
  // in the same statement, so records that must have an owner are kept.
  const requiredLinks = models.filter((m) => m !== model).flatMap((m) => m.fields.filter((f) => f.link === model.name && !f.optional).map((f) => ({ m, f })));
  const ghostFields = model.fields.filter((f) => f.link !== model.name).map((f) => ({ f, value: ghostValue(f) }));
  const ghostPossible = ghostFields.every((g) => g.value !== undefined);
  let ghost: GhostSpec | null = null;
  if (requiredLinks.length > 0 && ghostPossible) {
    const filled = ghostFields.flatMap((g) => (g.value === null || g.value === undefined ? [] : [{ f: g.f, value: g.value }]));
    ghost = {
      sql: `INSERT INTO ${table} (${filled.map((g) => q(g.f.column)).join(", ")}) VALUES (${filled.map((_, i) => `$${i + 1}`).join(", ")}) RETURNING ${q("id")}`,
      fields: filled.map((g) => ({ key: g.f.name, value: g.value })),
      removeSql: `DELETE FROM ${table} WHERE ${q("id")} = $1`,
    };
  }
  const deleteSql = accountDeleteSql(model, models, ghost !== null, false);
  return {
    model: model.name,
    account: {
      password: { ...fieldSpec(auth.passwordField, true), key: "newPassword" },
      hashSql: `SELECT ${q(auth.passwordField.column)} AS "hash" FROM ${table} WHERE ${q("id")} = $1`,
      setPasswordSql: `UPDATE ${table} SET ${q(auth.passwordField.column)} = $2 WHERE ${q("id")} = $1`,
      emailSql: `SELECT ${q(auth.loginField.column)} AS "email" FROM ${table} WHERE ${q("id")} = $1`,
      setEmailSql: `UPDATE ${table} SET ${q(auth.loginField.column)} = $2 WHERE ${q("id")} = $1`,
      deleteSql,
      ghost,
      profile: profileFields.length === 0
        ? null
        : {
            body: profileFields.map((f) => fieldSpec(f, false, model)),
            ...(fileFields(model, profileFields, { from: "me" }).length > 0 ? { files: fileFields(model, profileFields, { from: "me" }) } : {}),
            sql: `UPDATE ${table} SET ${sets.join(", ")} WHERE ${q("id")} = ${id} RETURNING ${select.sql}`,
            values: pp.values,
          },
    },
    signup: {
      body: fields.map((f) => fieldSpec(f, !f.optional)),
      // The account and its "email not confirmed yet" mark are created in one statement.
      sql: `WITH "created" AS (INSERT INTO ${table} (${cols.join(", ")}) VALUES (${vals.join(", ")}) RETURNING ${select.sql}), ` +
        `"pending" AS (INSERT INTO ${q(UNVERIFIED_TABLE)} ("user_id") SELECT "id" FROM "created") ` +
        `SELECT ${select.keys.map(quoteKey).join(", ")} FROM "created"`,
      values: p.values,
    },
    export: {
      account: { sql: `SELECT ${exportSelect(model, auth.roles.length > 0)} FROM ${table} WHERE ${q("id")} = $1`, ...encryptedOf(model) },
      records: models.filter((m) => m !== model).flatMap((m) => {
        const links = m.fields.filter((f) => f.link === model.name);
        if (links.length === 0) return [];
        const where = links.map((f) => `${q(f.column)} = $1`).join(" OR ");
        return [{ model: m.name, sql: `SELECT ${exportSelect(m, false)} FROM ${q(m.table)} WHERE ${where} ORDER BY ${q("id")} LIMIT 10001`, ...encryptedOf(m) }];
      }),
    },
    loginKey: auth.loginField.name,
    passwordKey: auth.passwordField.name,
    loginSql: `SELECT ${q("id")}, ${q(auth.passwordField.column)} AS "hash" FROM ${table} WHERE ${q(auth.loginField.column)} = $1`,
    meSql: `SELECT ${select.sql} FROM ${table} WHERE ${q("id")} = $1`,
    // A private login field is never sent, not even to its owner (SPEC §7).
    nameSql: auth.loginField.private ? "" : `SELECT ${q(auth.loginField.column)} AS "name" FROM ${table} WHERE ${q("id")} = $1`,
    publicKeys: select.keys,
    ...(encryptedFields(model).length > 0 ? { encrypted: encryptedFields(model) } : {}),
    roles: auth.roles,
    roleSql: auth.roles.length > 0 ? `SELECT ${q("role")} FROM ${table} WHERE ${q("id")} = $1` : "",
    setRoleSql: auth.roles.length > 0 ? `UPDATE ${table} SET ${q("role")} = $2 WHERE ${q("id")} = $1 RETURNING ${q("id")}, ${q("role")}` : "",
    grantAdminSql: auth.roles.length > 0
      ? `UPDATE ${table} SET ${q("role")} = ${roleLiteral("admin")} WHERE ${q(auth.loginField.column)} = ANY($1) AND ${q("role")} IS DISTINCT FROM ${roleLiteral("admin")}`
      : "",
  };
}
