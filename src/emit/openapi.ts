import type { ResolvedApi, ResolvedAuth } from "../check-api.js";
import { type ResolvedField, type ResolvedModel, isHidden } from "../checker.js";
import { FIELD_TYPES } from "../types.js";
import { VERSION } from "../version.js";
import type { FieldKind, FieldSpec, Route } from "../../runtime/types.ts";
import { buildApp } from "./routes.js";

/**
 * Emits `openapi.json` (OpenAPI 3.1): every endpoint with its parameters,
 * exact request body, public response fields, errors, and Rizo's access
 * rules as `x-rizo-*` extensions, so agents and tools know how to call the
 * API, and what they may call, before trying.
 *
 * It is built from the same route data the server runs on, so the two can't
 * disagree.
 */
export function emitOpenApi(apis: readonly ResolvedApi[], auth: ResolvedAuth | undefined, sourceFile: string): string {
  const app = buildApp(apis, auth);
  const models = new Map<string, ResolvedModel>();
  for (const api of apis) models.set(api.query.model.name, api.query.model);

  const paths: Record<string, Record<string, unknown>> = {};
  const usedIds = new Set<string>();
  apis.forEach((api, i) => {
    const route = app.routes[i];
    if (route === undefined) throw new Error("route missing");
    const path = api.path.replace(/:([A-Za-z][A-Za-z0-9]*)/g, "{$1}");
    paths[path] ??= {};
    (paths[path] as Record<string, unknown>)[api.method.toLowerCase()] = operation(api, route, uniqueId(api, usedIds));
  });

  const schemas: Record<string, unknown> = {
    Error: {
      type: "object",
      required: ["error"],
      properties: {
        error: {
          type: "object",
          required: ["code", "message"],
          properties: {
            code: { type: "string", description: "A stable code, e.g. validation_failed or not_found." },
            message: { type: "string", description: "What went wrong, for people." },
            field: { type: "string", description: "The body field or parameter at fault, when there is one." },
          },
        },
      },
    },
  };
  for (const model of [...models.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    const fields = model.fields.filter((f) => !isHidden(f));
    schemas[`${model.name}Public`] = {
      type: "object",
      description: `${model.name}.public: the fields of a ${model.name} that are returned. Password and private fields never are.`,
      required: ["id", ...fields.map((f) => f.name)],
      properties: { id: { type: "string", format: "uuid" }, ...Object.fromEntries(fields.map((f) => [f.name, fieldSchema(f)])) },
      additionalProperties: false,
    };
  }

  const doc = {
    openapi: "3.1.0",
    info: {
      title: sourceFile.replace(/\.rz$/, ""),
      version: "1",
      description: [
        `Generated by rizolang ${VERSION} from ${sourceFile}. Do not edit by hand.`,
        "Endpoints marked x-rizo-access: login accept the session cookie or an API token (Authorization: Bearer rzt_...).",
        "A token works only on the endpoints it was created for. Account endpoints under /auth are described in the Rizo Lang spec, and never accept tokens.",
        "Request bodies are strict: unknown fields are rejected with 400.",
      ].join(" "),
    },
    // Relative: the same server that serves this document, wherever the app runs.
    servers: [{ url: "/", description: "The server that serves this document." }],
    paths,
    components: {
      schemas,
      securitySchemes: {
        session: { type: "apiKey", in: "cookie", name: "rizo_session", description: "The session cookie set by POST /auth/login." },
        token: {
          type: "http",
          scheme: "bearer",
          description: "An API token (rzt_...) created on the account page or with POST /auth/tokens. It works only on the endpoints chosen for it, for at most 90 days.",
        },
      },
    },
  };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

function operation(api: ResolvedApi, route: Route, operationId: string): Record<string, unknown> {
  const model = api.query.model;
  const errors: Record<string, string> = {
    "400": "The request is not valid (body, parameter or page cursor).",
    ...(api.access === "login" ? { "401": "Not logged in, or the API token is not valid or has expired." } : {}),
    ...(api.access === "login" ? { "403": `Not allowed${route.roles.length > 0 ? ` (needs role ${route.roles.join(" or ")})` : ""}, or the API token was not created for this endpoint.` } : {}),
    ...(api.returns !== "list" ? { "404": `${model.name} not found${api.owner !== undefined ? ", or it isn't yours" : ""}.` } : {}),
    ...(api.method !== "GET" && api.query.action !== "update" ? { "409": "The change conflicts with existing data (a duplicate unique value, or other records link to it)." } : {}),
    "429": "Too many requests. Wait for the number of seconds in Retry-After.",
    "503": "The server is busy, or the request took too long. Retry after Retry-After seconds.",
  };
  const responses: Record<string, unknown> = {};
  const ref = { $ref: `#/components/schemas/${model.name}Public` };
  if (route.result === "list") {
    responses["200"] = {
      description: `A page of ${model.name} records. Pass next as ?after= to get the following page.`,
      content: { "application/json": { schema: {
        type: "object",
        required: ["items", "next"],
        properties: { items: { type: "array", items: ref }, next: { type: ["string", "null"], description: "Cursor for the next page, or null on the last page." } },
      } } },
    };
  } else if (route.result === "none") {
    responses["204"] = { description: `The ${model.name} was deleted.` };
  } else {
    responses[route.result === "created" ? "201" : "200"] = {
      description: route.result === "created" ? `The new ${model.name}.` : `The ${model.name}.`,
      content: { "application/json": { schema: ref } },
    };
  }
  for (const [status, description] of Object.entries(errors)) {
    responses[status] = { description, content: { "application/json": { schema: { $ref: "#/components/schemas/Error" } } } };
  }

  const parameters: unknown[] = route.path.flatMap((part) =>
    "param" in part ? [{ name: part.param, in: "path", required: true, schema: paramSchema(part.kind) }] : []);
  for (const qp of route.query ?? []) {
    const uses = api.query.action === "list" ? api.query.filters.filter((f) => f.value.kind === "query" && f.value.name === qp.name) : [];
    parameters.push({
      name: qp.name, in: "query", required: false,
      description: `Optional filter: ${uses.map((f) => `${f.field.name} ${f.op} ${qp.name}`).join(", ")}. Left out, the filter is skipped.`,
      schema: qp.kind === "Text" ? { type: "string", minLength: 1, maxLength: 200 } : kindSchema(qp.kind, false),
    });
  }
  if (route.page !== null) {
    parameters.push(
      { name: "limit", in: "query", required: false, description: `Page size (default and maximum ${route.page.max}).`, schema: { type: "integer", minimum: 1, maximum: route.page.max } },
      { name: "after", in: "query", required: false, description: "The next value of the previous page.", schema: { type: "string" } },
    );
  }

  return {
    operationId,
    summary: `${summaryVerb(api)} ${model.name}${api.returns === "list" ? " records" : ""}`,
    ...(parameters.length > 0 ? { parameters } : {}),
    ...(route.body !== null ? { requestBody: requestBody(route.body, model, api.query.action === "update") } : {}),
    responses,
    security: api.access === "login" ? [{ session: [] }, { token: [] }] : [],
    "x-rizo-access": api.access,
    ...(route.roles.length > 0 ? { "x-rizo-roles": route.roles } : {}),
    ...(api.owner !== undefined
      ? { "x-rizo-owner": { field: api.owner.name, ...(api.ownerBypassRoles.length > 0 ? { orRoles: api.ownerBypassRoles } : {}) } }
      : {}),
    "x-rizo-rate-limit": { requests: route.rateLimit.max, perSeconds: route.rateLimit.windowSeconds },
  };
}

function requestBody(body: readonly FieldSpec[], model: ResolvedModel, partial: boolean): Record<string, unknown> {
  const required = body.filter((f) => f.required).map((f) => f.key);
  return {
    required: true,
    description: partial ? "Only the fields to change. Fields that are left out keep their value." : undefined,
    content: { "application/json": { schema: {
      type: "object",
      ...(required.length > 0 ? { required } : {}),
      properties: Object.fromEntries(body.map((spec) => {
        const field = model.fields.find((f) => f.name === spec.key);
        return [spec.key, specSchema(spec, field)];
      })),
      additionalProperties: false,
    } } },
  };
}

/** Schema for a stored field, as it appears in responses. */
function fieldSchema(f: ResolvedField): Record<string, unknown> {
  const s = kindSchema(f.type, f.link !== undefined);
  const info = FIELD_TYPES[f.type];
  if (info.length !== undefined) {
    if (f.min !== undefined && f.min > 0) s["minLength"] = f.min;
    if (f.max !== undefined) s["maxLength"] = f.max;
  } else if (info.valueRange !== undefined) {
    s["minimum"] = f.min ?? info.valueRange.lowest;
    s["maximum"] = f.max ?? info.valueRange.highest;
  }
  if (f.link !== undefined) s["description"] = `The id of a ${f.link}.`;
  return f.optional ? { ...s, type: [s["type"], "null"] } : s;
}

/** Schema for a body field, with the same limits the server checks. */
function specSchema(spec: FieldSpec, field: ResolvedField | undefined): Record<string, unknown> {
  const s = kindSchema(spec.kind, field?.link !== undefined);
  const lengthLike = spec.kind === "Text" || spec.kind === "Email" || spec.kind === "Password";
  if (spec.min !== undefined) s[lengthLike ? "minLength" : "minimum"] = spec.min;
  if (spec.max !== undefined) s[lengthLike ? "maxLength" : "maximum"] = spec.max;
  if (spec.kind === "Number") {
    s["minimum"] ??= FIELD_TYPES.Number.valueRange?.lowest;
    s["maximum"] ??= FIELD_TYPES.Number.valueRange?.highest;
  }
  if (spec.kind === "Password") s["description"] = "Stored only as a salted hash, and never returned.";
  if (field?.link !== undefined) s["description"] = `The id of a ${field.link}.`;
  return spec.nullable ? { ...s, type: [s["type"], "null"] } : s;
}

function kindSchema(kind: FieldKind, link: boolean): Record<string, unknown> {
  if (link) return { type: "string", format: "uuid" };
  switch (kind) {
    case "Text": return { type: "string" };
    case "Password": return { type: "string", format: "password", writeOnly: true };
    case "Email": return { type: "string", format: "email" };
    case "Number": return { type: "integer" };
    case "Bool": return { type: "boolean" };
    case "Date": return { type: "string", format: "date-time" };
    case "ID": return { type: "string", format: "uuid" };
  }
}

function paramSchema(kind: "ID" | "Number" | "Bool" | "Text" | "Email"): Record<string, unknown> {
  return kindSchema(kind, false);
}

function summaryVerb(api: ResolvedApi): string {
  switch (api.query.action) {
    case "find": return "Get a";
    case "list": return "List";
    case "create": return "Create a";
    case "update": return "Update a";
    case "delete": return "Delete a";
  }
}

/** `getApiPostsById`-style ids, unique within the document. */
function uniqueId(api: ResolvedApi, used: Set<string>): string {
  const words = api.path.split("/").filter(Boolean).map((s) => (s.startsWith(":") ? `by-${s.slice(1)}` : s));
  const camel = [api.method.toLowerCase(), ...words.flatMap((w) => w.split("-"))]
    .map((w, i) => (i === 0 ? w : w.charAt(0).toUpperCase() + w.slice(1)))
    .join("");
  let id = camel;
  for (let n = 2; used.has(id); n++) id = `${camel}${n}`;
  used.add(id);
  return id;
}
